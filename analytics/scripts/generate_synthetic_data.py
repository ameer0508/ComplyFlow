"""
ComplyFlow - Synthetic Data Generator
====================================
Generates realistic, reproducible synthetic compliance operations datasets
strictly following the approved Phase 2A domain model:
1. ComplianceRequest (150 records)
2. RequestAuditLog (milestone audit events)
3. SLAPolicy (4 reference tiers)

DISCLAIMER:
All entities, names, identifiers, transactions, and scenarios generated by
this script are 100% synthetic and fictional. They do not represent real
financial-services customer data, proprietary systems, or StoneX Group data.
"""

import csv
